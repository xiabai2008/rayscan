    def generate_plugin_structure(self, plugin_name: str, 
                                  files: Dict[str, str],
                                  output_dir: str = './plugins') -> str:
        """生成插件目录结构"""
        
        plugin_id = plugin_name.lower().replace(' ', '-')
        plugin_dir = os.path.join(output_dir, plugin_id)
        
        os.makedirs(plugin_dir, exist_ok=True)
        
        for filename, content in files.items():
            filepath = os.path.join(plugin_dir, filename)
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(content)
        
        return plugin_dir
    
    def validate_plugin(self, plugin_path: str) -> Dict[str, Any]:
        """验证插件合规性"""
        
        results = {
            'is_valid': False,
            'details': {},
            'certification_status': 'needs_review',
        }
        
        # 1. 安全检查
        results['details']['security_check'] = self._run_security_check(plugin_path)
        
        # 2. API兼容性检查
        results['details']['api_compatibility'] = self._check_api_compatibility(plugin_path)
        
        # 3. 文档检查
        results['details']['documentation_check'] = self._check_documentation(plugin_path)
        
        # 4. 代码质量检查
        results['details']['code_quality'] = self._check_code_quality(plugin_path)
        
        # 综合判断
        all_passed = all(results['details'].values())
        results['is_valid'] = all_passed
        results['certification_status'] = 'certified' if all_passed else 'needs_review'
        
        return results
    
    def _run_security_check(self, plugin_path: str) -> bool:
        """运行安全检查"""
        # 检查危险代码模式
        dangerous_patterns = [
            'eval(',
            'exec(',
            '__import__',
            'os.system',
            'subprocess.call',
        ]
        
        plugin_file = os.path.join(plugin_path, 'plugin.py')
        if os.path.exists(plugin_file):
            with open(plugin_file, 'r', encoding='utf-8') as f:
                content = f.read()
            
            for pattern in dangerous_patterns:
                if pattern in content:
                    return False
        
        return True
    
    def _check_api_compatibility(self, plugin_path: str) -> bool:
        """检查API兼容性"""
        # 检查是否正确继承基类
        plugin_file = os.path.join(plugin_path, 'plugin.py')
        if os.path.exists(plugin_file):
            with open(plugin_file, 'r', encoding='utf-8') as f:
                content = f.read()
            
            # 应该继承WVSPlugin或其子类
            if 'WVSPlugin' not in content and 'ScannerPlugin' not in content:
                return False
        
        return True
    
    def _check_documentation(self, plugin_path: str) -> bool:
        """检查文档"""
        readme_path = os.path.join(plugin_path, 'README.md')
        return os.path.exists(readme_path)
    
    def _check_code_quality(self, plugin_path: str) -> bool:
        """检查代码质量"""
        # 简化检查：文件是否存在且非空
        plugin_file = os.path.join(plugin_path, 'plugin.py')
        if os.path.exists(plugin_file):
            return os.path.getsize(plugin_file) > 100
        return False
    
    def package_plugin(self, plugin_path: str, output_dir: str = './dist') -> str:
        """打包插件"""
        import zipfile
        
        plugin_name = os.path.basename(plugin_path)
        output_file = os.path.join(output_dir, f'{plugin_name}.wvs-plugin')
        
        os.makedirs(output_dir, exist_ok=True)
        
        with zipfile.ZipFile(output_file, 'w', zipfile.ZIP_DEFLATED) as zf:
            for root, dirs, files in os.walk(plugin_path):
                for file in files:
                    file_path = os.path.join(root, file)
                    arcname = os.path.relpath(file_path, plugin_path)
                    zf.write(file_path, arcname)
        
        return output_file
