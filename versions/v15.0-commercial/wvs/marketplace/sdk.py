from abc import ABC, abstractmethod


class WVSPlugin(ABC):
    """WVS插件基类"""
    
    @property
    @abstractmethod
    def name(self) -> str:
        """插件名称"""
        pass
    
    @property
    @abstractmethod
    def version(self) -> str:
        """插件版本"""
        pass
    
    @property
    @abstractmethod
    def description(self) -> str:
        """插件描述"""
        pass
    
    @property
    def author(self) -> str:
        """插件作者"""
        return "Unknown"
    
    @property
    def dependencies(self) -> List[str]:
        """依赖插件列表"""
        return []
    
    @property
    def min_wvs_version(self) -> str:
        """最低WVS版本"""
        return "11.0.0"
    
    def initialize(self, config: Dict[str, Any]) -> bool:
        """初始化插件"""
        return True
    
    def shutdown(self):
        """关闭插件"""
        pass


class ScannerPlugin(WVSPlugin):
    """扫描器插件基类"""
    
    @abstractmethod
    def scan(self, target: str, options: Dict) -> Dict[str, Any]:
        """执行扫描"""
        pass
    
    @property
    def supported_targets(self) -> List[str]:
        """支持的目标类型"""
        return ['url']


class ReporterPlugin(WVSPlugin):
    """报告插件基类"""
    
    @abstractmethod
    def generate(self, scan_results: Dict, output_path: str) -> str:
        """生成报告"""
        pass
    
    @property
    def supported_formats(self) -> List[str]:
        """支持的格式"""
        return ['html']


class NotifierPlugin(WVSPlugin):
    """通知插件基类"""
    
    @abstractmethod
    def notify(self, message: str, severity: str, config: Dict) -> bool:
        """发送通知"""
        pass


